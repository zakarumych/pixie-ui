pub(super) const GLYPH_W: i32 = 5;
pub(super) const GLYPH_H: i32 = 7;
/// Bitmap canvas height, padded from GLYPH_H to make each glyph column exactly one byte tall.
pub(super) const BITMAP_H: i32 = 8;
pub(super) const BYTES_PER_GLYPH: usize =
    (((GLYPH_W * BITMAP_H) as u32).next_multiple_of(32) / 8) as usize;

pub(super) fn mono5x7_bitmap() -> Bitmap {
    let mut bitmap = vec![0u8; FONT_MONO_5X7.len() * BYTES_PER_GLYPH];

    // Column-major: byte x holds column x, bit y (0 = top) set if that pixel is on.
    // Row 7 is always blank padding, so bit 7 stays 0.
    for (i, glyph) in FONT_MONO_5X7.iter().enumerate() {
        let base = i * BYTES_PER_GLYPH;
        for (y, &row) in glyph.iter().enumerate() {
            for x in 0..GLYPH_W {
                if (row >> (GLYPH_W - 1 - x)) & 1 != 0 {
                    bitmap[base + x as usize] |= 1 << y;
                }
            }
        }
    }

    Bitmap {
        glyph_size: Size {
            w: GLYPH_W,
            h: BITMAP_H,
        },
        bitmap: bitmap.into_boxed_slice(),
    }
}

pub(super) fn mono5x7_mapping() -> HashMap<char, u32, RandomState> {
    let mut mapping =
        HashMap::with_capacity_and_hasher(FONT_MONO_5X7.len(), RandomState::default());
    for i in 0..FONT_MONO_5X7.len() as u32 {
        mapping.insert(char::from_u32(0x20 + i).unwrap(), i);
    }
    mapping
}

pub fn mono5x7() -> Font {
    let glyph_metrics: Box<[Metrics]> = (0..FONT_MONO_5X7.len())
        .map(|_| Metrics {
            advance: Size {
                w: GLYPH_W + 1,
                h: GLYPH_H + 1,
            },
            offset: Vec::ZERO,
            bbox: Rect {
                lt: Pos { x: 0, y: 0 },
                rb: Pos {
                    x: GLYPH_W as i32,
                    y: GLYPH_H as i32,
                },
            },
        })
        .collect();

    Font {
        name: "mono5x7".into(),
        size: Size {
            w: GLYPH_W,
            h: GLYPH_H,
        },
        gap: Vec { x: 0, y: 1 },
        glyph_metrics,
        bitmap: mono5x7_bitmap(),
        mapping: mono5x7_mapping(),
    }
}
